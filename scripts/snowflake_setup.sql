-- Snowflake bootstrap for saas-product-analytics
-- Run this once in Snowsight (Worksheets) as a user with SYSADMIN + SECURITYADMIN privileges.
-- After it succeeds, fill the matching values in .env (use .env.example as a template).
--
-- IMPORTANT: replace <REPLACE_WITH_STRONG_PASSWORD> below before running. This file is committed —
-- the placeholder must NEVER be replaced with a real password in this checked-in copy.
-- Keep the real password only in your local .env (which is gitignored).

USE ROLE SYSADMIN;

-- Compute: small warehouse, suspends after 60s of inactivity.
-- XSMALL is plenty for ~220K rows; auto-suspend keeps trial credits alive.
CREATE OR REPLACE WAREHOUSE TRANSFORMING_WH
  WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Storage: one database, four schemas (mirrors the dbt project layout).
CREATE OR REPLACE DATABASE ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.RAW;      -- landing zone for CSV loads
CREATE SCHEMA IF NOT EXISTS ANALYTICS.STAGING;  -- dbt staging models
CREATE SCHEMA IF NOT EXISTS ANALYTICS.MARTS;    -- dbt marts models
CREATE SCHEMA IF NOT EXISTS ANALYTICS.CI;       -- dedicated schema for GitHub Actions CI runs

-- Role for dbt + analytics access.
USE ROLE SECURITYADMIN;
CREATE OR REPLACE ROLE TRANSFORMER;

GRANT USAGE ON WAREHOUSE TRANSFORMING_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON ALL SCHEMAS IN DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT
  ON FUTURE SCHEMAS IN DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES
  IN DATABASE ANALYTICS TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ANALYTICS TO ROLE TRANSFORMER;

-- User: dbt runs as this user (both locally and in CI).
CREATE OR REPLACE USER DBT_USER
  PASSWORD = '<REPLACE_WITH_STRONG_PASSWORD>'
  DEFAULT_ROLE = TRANSFORMER
  DEFAULT_WAREHOUSE = TRANSFORMING_WH
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE TRANSFORMER TO USER DBT_USER;

-- Smoke test — confirm the role is wired up correctly.
USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORMING_WH;
USE DATABASE ANALYTICS;
SELECT CURRENT_USER(), CURRENT_ROLE(), CURRENT_WAREHOUSE(), CURRENT_DATABASE();
